/**
 * Gets a deterministic quote based on the current calendar date string (YYYY-MM-DD)
 */
export function getDailyQuoteForDate(isoDateString?: string): DailyQuoteItem {
  const dateStr = isoDateString || new Date().toISOString().split('T')[0];
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % DAILY_QUOTES.length;
  return DAILY_QUOTES[index];
}
